import { describe, it, expect, vi } from 'vitest';
import * as fc from 'fast-check';
import { WeatherControllerImpl } from './WeatherController.js';
import { StateManager } from './StateManager.js';
import type {
  Coordinates,
  ForecastData,
  GeocodingService,
  WeatherService,
  InputValidator,
} from '../types.js';

// ─────────────────────────────────────────────────────────────────────────────
// Property 4: Cadena de llamadas API usa parámetros correctos
// Feature: weather-forecast-app, Property 4: Cadena de llamadas API usa parámetros correctos
//
// Validates: Requirements 2.1, 2.2, 2.3, 3.1
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Generator for Property 4.
 * Produces arbitrary (lat, lon, name) triples representing geocoding results.
 * - lat / lon: finite floats (no NaN, no ±Infinity) — values the Geocoding API returns
 * - name: non-empty string — the canonical city name returned by the Geocoding API
 */
const coordsResultArb = fc.record({
  lat: fc.float({ noNaN: true, noDefaultInfinity: true }),
  lon: fc.float({ noNaN: true, noDefaultInfinity: true }),
  name: fc.string({ minLength: 1 }),
});

/** A minimal valid ForecastData stub returned by the WeatherService mock. */
const stubForecast: ForecastData = {
  cityName: 'stub-city',
  temperatureCelsius: 20,
  relativeHumidityPercent: 50,
  precipitationMm: 0,
};

// ─────────────────────────────────────────────────────────────────────────────

describe('Property 4 — API call chain uses correct parameters (Req 2.1, 2.2, 2.3, 3.1)', () => {
  // Feature: weather-forecast-app, Property 4: Cadena de llamadas API usa parámetros correctos

  it(
    'geocode() receives the exact cityName and getForecast() receives the exact coordinates returned by geocode()',
    async () => {
      await fc.assert(
        fc.asyncProperty(
          // The city name the user types in (must be non-empty so the validator passes)
          fc.string({ minLength: 1 }),
          // The lat/lon/name the Geocoding API will return for that city
          coordsResultArb,
          async (cityName, { lat, lon, name }) => {
            // ── Build mocks ───────────────────────────────────────────────

            // InputValidator: always returns null (valid) so the controller
            // never short-circuits before calling the services.
            const validator: InputValidator = {
              validate: vi.fn().mockReturnValue(null),
            };

            // GeocodingService: captures the argument it was called with and
            // returns the coordinates generated by the property test.
            const geocodingService: GeocodingService = {
              geocode: vi.fn().mockResolvedValue({
                latitude: lat,
                longitude: lon,
                cityName: name,
              } satisfies Coordinates),
            };

            // WeatherService: captures the Coordinates argument and returns a
            // valid ForecastData stub so the controller can complete successfully.
            const weatherService: WeatherService = {
              getForecast: vi.fn().mockResolvedValue(stubForecast),
            };

            // Real StateManager — only the spy call assertions matter here.
            const stateManager = new StateManager();

            // ── Run the controller ────────────────────────────────────────

            const controller = new WeatherControllerImpl(
              validator,
              geocodingService,
              weatherService,
              stateManager,
            );

            await controller.search(cityName);

            // ── Assertion (a): geocode was called with the exact cityName ─
            // Req 2.1 — the Geocoding API is called with exactly the user-supplied city name.
            expect(geocodingService.geocode).toHaveBeenCalledOnce();
            expect(geocodingService.geocode).toHaveBeenCalledWith(cityName);

            // ── Assertion (b): getForecast was called with the coordinates
            //    returned by geocode()                                       ─
            // Req 2.2, 2.3 — latitude and longitude from results[0] are
            // forwarded verbatim to the Weather API call.
            // Req 3.1 — getForecast() is called after a successful geocode().
            expect(weatherService.getForecast).toHaveBeenCalledOnce();

            const passedCoords: Coordinates =
              (weatherService.getForecast as ReturnType<typeof vi.fn>).mock.calls[0][0];

            expect(passedCoords.latitude).toBe(lat);
            expect(passedCoords.longitude).toBe(lon);

            // ── Assertion (c): the WeatherService call includes a complete
            //    Coordinates object (lat + lon + cityName), confirming the
            //    controller forwards all three required variables so the
            //    service can construct the URL with temperature_2m,
            //    relative_humidity_2m and precipitation.
            // Req 2.3 — the call includes the three required weather variables.
            expect(typeof passedCoords.latitude).toBe('number');
            expect(typeof passedCoords.longitude).toBe('number');
            expect(typeof passedCoords.cityName).toBe('string');
          },
        ),
        { numRuns: 100 },
      );
    },
  );

  it(
    'geocode() and getForecast() are each called exactly once per valid search',
    async () => {
      // Feature: weather-forecast-app, Property 4: Cadena de llamadas API usa parámetros correctos
      await fc.assert(
        fc.asyncProperty(
          fc.string({ minLength: 1 }),
          coordsResultArb,
          async (cityName, { lat, lon, name }) => {
            const validator: InputValidator = {
              validate: vi.fn().mockReturnValue(null),
            };
            const geocodingService: GeocodingService = {
              geocode: vi.fn().mockResolvedValue({
                latitude: lat,
                longitude: lon,
                cityName: name,
              } satisfies Coordinates),
            };
            const weatherService: WeatherService = {
              getForecast: vi.fn().mockResolvedValue(stubForecast),
            };

            const controller = new WeatherControllerImpl(
              validator,
              geocodingService,
              weatherService,
              new StateManager(),
            );

            await controller.search(cityName);

            // Req 2.1 — geocode is called exactly once; it is never skipped.
            expect(geocodingService.geocode).toHaveBeenCalledTimes(1);

            // Req 3.1 — getForecast is called exactly once after geocode succeeds.
            expect(weatherService.getForecast).toHaveBeenCalledTimes(1);
          },
        ),
        { numRuns: 100 },
      );
    },
  );

  it(
    'getForecast() is NOT called when geocode() fails (call chain is strictly sequential)',
    async () => {
      // Feature: weather-forecast-app, Property 4: Cadena de llamadas API usa parámetros correctos
      // Req 3.1 — the Weather API is only called after a successful geocode.
      await fc.assert(
        fc.asyncProperty(
          fc.string({ minLength: 1 }),
          async (cityName) => {
            const validator: InputValidator = {
              validate: vi.fn().mockReturnValue(null),
            };
            const geocodingService: GeocodingService = {
              geocode: vi.fn().mockRejectedValue(new Error('network failure')),
            };
            const weatherService: WeatherService = {
              getForecast: vi.fn(),
            };

            const controller = new WeatherControllerImpl(
              validator,
              geocodingService,
              weatherService,
              new StateManager(),
            );

            await controller.search(cityName);

            // geocode was attempted
            expect(geocodingService.geocode).toHaveBeenCalledTimes(1);
            // getForecast must NOT have been called — the chain stops on geocode failure
            expect(weatherService.getForecast).not.toHaveBeenCalled();
          },
        ),
        { numRuns: 100 },
      );
    },
  );
});
